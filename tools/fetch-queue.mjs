#!/usr/bin/env node
/*
  Refreshes the Culture Log's movies and TV from Jordan's public Queue profile (queue.co/users/seezynn):
    - WATCH in docs/js/data.js: every watched title by rating, newest first (~ prefix = TV show)
    - WATCHED in docs/js/data.js: the newest 40 watched, with dates
    - REVIEWS in docs/js/data.js: every title with a written review, newest first
    - posters: downloaded once into docs/assets/covers/ (self-hosted, from TMDB's image server) and mapped in docs/js/covers.js

    node tools/fetch-queue.mjs                 # everything
    node tools/fetch-queue.mjs --no-posters    # data only
*/
import {writeFileSync,readFileSync,existsSync,mkdirSync} from 'node:fs';
import {join,resolve} from 'node:path';

const root=resolve(new URL('..',import.meta.url).pathname),SITE=join(root,'docs');
const dataJs=join(SITE,'js/data.js'),coversJs=join(SITE,'js/covers.js'),outDir=join(SITE,'assets/covers');
const API='https://www.queue.co/api/cache/public/feed?user_handle=seezynn&limit=28&watched_latest_action=true';
const RATE={LOVE:'love',LIKE:'like',MEH:'meh',DISLIKE:'dislike',WATCHED_NEUTRAL:'none'};
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const slug=s=>s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'').slice(0,80);
const posters=!process.argv.includes('--no-posters');

async function feed(q){
  const out=[];let tok='';
  for(let i=0;i<100;i++){
    const r=await fetch(API+q+(tok?'&page_token='+tok:''));if(!r.ok)throw new Error('Queue HTTP '+r.status);
    const j=await r.json();out.push(...j.data);
    if(j.meta.last||!j.meta.next)break;tok=j.meta.next;await sleep(400);
  }
  return out;
}
const row=x=>({id:x.title.id,title:x.title.title,t:x.title.type==='SHOW'?'tv':'movie',rate:RATE[x.action.type]||'none',date:x.timestamp.slice(0,10),poster:x.title.posterImage&&x.title.posterImage.id,text:(x.action.comment||'').trim()});

const watched=(await feed('&title_action=WATCHED&include_watched_neutral=true')).map(row);
const reviews=(await feed('&with_review=true')).map(row).filter(r=>r.text);
console.log('Watched',watched.length,'titles;',reviews.length,'with reviews');

/* WATCH: rating buckets, newest first, ~ marks TV (one entry per title) */
const seen=new Set(),buckets={love:[],like:[],meh:[],dislike:[],none:[]};
for(const w of watched){const k=w.id;if(seen.has(k))continue;seen.add(k);buckets[w.rate].push((w.t==='tv'?'~':'')+w.title.replace(/\|/g,'/'));}
const WATCH=Object.fromEntries(Object.entries(buckets).map(([k,v])=>[k,v.join('|')]));
const WATCHED=watched.slice(0,40).map(w=>[w.title,w.t,w.rate,w.date]);
const REVIEWS=reviews.map(r=>[r.title,r.t,r.rate,r.date,r.text]);

let src=readFileSync(dataJs,'utf8');
const put=(name,val,note)=>{
  const line=(note?'/* '+note+' */\n':'')+'export const '+name+'='+JSON.stringify(val)+';';
  const re=new RegExp('(?:/\\*[^\\n]*\\*/\\n)?export const '+name+'=.*;');
  src=re.test(src)?src.replace(re,()=>line):src.replace(/(export const WATCH=.*;)/,m=>m+'\n'+line);
};
put('WATCH',WATCH);
put('WATCHED',WATCHED,'newest watched first, from Queue: [title, movie|tv, rating, date watched]');
put('REVIEWS',REVIEWS,'titles with a written review on Queue, newest first: [title, movie|tv, rating, date, review]');
writeFileSync(dataJs,src);

/* posters: TMDB paths ride inside Queue's image ids ("TMDB,/abc.jpg" in base64url) */
if(posters){
  mkdirSync(outDir,{recursive:true});
  let covers={};
  if(existsSync(coversJs)){try{covers=JSON.parse(readFileSync(coversJs,'utf8').replace(/^[^{]*/,'').replace(/;?\s*$/,''));}catch{}}
  let got=0,miss=[];
  for(const w of watched){
    const key=w.t+':'+w.title.toLowerCase(),file=slug(w.t+'-'+w.title)+'.jpg';
    if(covers[key]&&existsSync(join(SITE,covers[key])))continue;
    let path='';try{path=Buffer.from(w.poster||'','base64url').toString().replace(/^TMDB,/,'');}catch{}
    if(!/^\/\w+\.(jpg|png)$/.test(path)){miss.push(w.title);continue;}
    try{
      if(!existsSync(join(outDir,file))){
        const r=await fetch('https://image.tmdb.org/t/p/w185'+path);if(!r.ok)throw new Error('HTTP '+r.status);
        writeFileSync(join(outDir,file),Buffer.from(await r.arrayBuffer()));await sleep(120);
      }
      covers[key]='assets/covers/'+file;got++;
    }catch(e){miss.push(w.title+' ('+e.message+')');}
  }
  writeFileSync(coversJs,'/* generated by tools/fetch-covers.mjs and tools/fetch-queue.mjs */\nwindow.COVERS='+JSON.stringify(covers)+';\n');
  console.log('Posters: saved',got,'new. No poster for',miss.length,miss.length?'('+miss.slice(0,8).join(', ')+')':'');
}
